def main():
    # 加载v2映射
    with open(V2_CSV, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    mapping = {r["gb_full_name"]: r for r in rows}
    print(f"原v2映射: {len(mapping)} 条")

    # 应用补丁
    patched = 0
    for gb, new_a in PATCHES.items():
        if gb in mapping:
            old = mapping[gb]["match_to"]
            if old != new_a:
                mapping[gb]["match_to"] = new_a
                mapping[gb]["reason"] = f"补正(原{old})"
                patched += 1
        else:
            mapping[gb] = {"gb_full_name": gb, "match_to": new_a, "reason": "补正新增"}
            patched += 1
    print(f"补正: {patched} 条")

    # 写回CSV
    with open(V2_CSV, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["gb_full_name", "match_to", "reason"])
        w.writeheader()
        for k in mapping:
            w.writerow(mapping[k])
    # 写回JSON
    mapping_dict = {k: v["match_to"] for k, v in mapping.items()}
    with open(V2_JSON, "w", encoding="utf-8") as f:
        json.dump(mapping_dict, f, ensure_ascii=False, indent=2)
    print(f"写入: {V2_CSV} / {V2_JSON}")
    print(f"总映射: {len(mapping)}")


if __name__ == "__main__":
    main()
