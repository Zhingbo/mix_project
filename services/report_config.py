    @classmethod
    def get_category_keywords(cls, category: str) -> List[str]:
        """获取分类关键词"""
        return cls.BASIC_CATEGORIES.get(category, [])
    
    @classmethod
    def get_detailed_chapter_keywords(cls, chapter: str) -> List[str]:
        """获取详细版章节关键词"""
        return cls.DETAILED_REPORT_CHAPTERS.get(chapter, [])
    
    @classmethod
    def get_simple_chapter_keywords(cls, chapter: str) -> List[str]:
        """获取精简版章节关键词"""
        return cls.SIMPLE_REPORT_CHAPTERS.get(chapter, [])
    
    @classmethod
    def get_all_categories(cls) -> List[str]:
        """获取所有分类标签"""
        return list(cls.BASIC_CATEGORIES.keys())
    
    @classmethod
    def get_all_detailed_chapters(cls) -> List[str]:
        """获取所有详细版章节"""
        return list(cls.DETAILED_REPORT_CHAPTERS.keys())
    
    @classmethod
    def get_all_simple_chapters(cls) -> List[str]:
        """获取所有精简版章节"""
        return list(cls.SIMPLE_REPORT_CHAPTERS.keys())
    
    @classmethod
    def get_chapter_keywords_by_template(cls, chapter: str, template_type: str = "detailed") -> List[str]:
        """根据模板类型获取章节关键词"""
        if template_type == "simple":
            return cls.get_simple_chapter_keywords(chapter)
        else:
            return cls.get_detailed_chapter_keywords(chapter)
    
    @classmethod
    def get_chapters_by_template(cls, template_type: str = "detailed") -> List[str]:
        """根据模板类型获取所有章节"""
        if template_type == "simple":
            return cls.get_all_simple_chapters()
        else:
            return cls.get_all_detailed_chapters()